from app.content.lesson_content import Practice, task


@dataclass(frozen=True)
class TrainerTask:
    id: str
    practice: Practice
    tags: tuple[str, ...]


def entry(
    number: int,
    title: str,
    difficulty: str,
    tags: str,
    description: str,
    solution: str,
    tests: tuple[tuple[str, str], ...],
    hint: str,
) -> TrainerTask:
    return TrainerTask(
        f"trainer-{number:02d}",
        task(title, description, solution, tests, hint, difficulty),
        tuple(tags.split()),
    )


